#!/usr/bin/env python3
"""Build the requirement-to-test trace matrix for a Libre RWS module.

Requirements are read from docs/dhf/<module>/SRS.md: table rows whose first
cell is an ID such as DCM-SRS-012, with a Status column (Active, Draft,
Retired). Tests declare what they verify with a comment directly above the
test function:

    // Verifies: DCM-SRS-012, DCM-SRS-013
    func TestSomething(t *testing.T) {

Manual verification (system tests, conformance runs) is declared in
docs/dhf/<module>/manual-verification.md with lines like:

    - DCM-SRS-040: scripts/conformance.sh (DCMTK), release system test

Usage:
    trace.py [--module libredcm] [--prefix DCM] [--check] [--write]

--write  writes docs/dhf/<module>/generated/trace-matrix.md
--check  exits 1 if an Active requirement has no verification, or a test
         references an unknown or retired ID.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]


def load_requirements(srs: pathlib.Path, prefix: str):
    reqs = {}
    pat = re.compile(rf"^\|\s*({prefix}-SRS-\d{{3}})\s*\|(.*)$")
    for line in srs.read_text(encoding="utf-8").splitlines():
        m = pat.match(line)
        if not m:
            continue
        cells = [c.strip() for c in m.group(2).split("|")]
        text = cells[0] if cells else ""
        status = next((c for c in cells if c in ("Active", "Draft", "Retired")), "Active")
        reqs[m.group(1)] = {"text": text, "status": status}
    return reqs


def scan_tests(prefix: str):
    """Return {req_id: [test refs]} from // Verifies: tags in *_test.go."""
    found = {}
    tag = re.compile(r"//\s*Verifies:\s*(.+)$")
    func = re.compile(r"^func\s+(Test\w+|Fuzz\w+|Benchmark\w+)\s*\(")
    idpat = re.compile(rf"{prefix}-SRS-\d{{3}}")
    for path in sorted(ROOT.rglob("*_test.go")):
        rel = path.relative_to(ROOT)
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        pending = []
        for line in lines:
            t = tag.search(line)
            if t:
                pending += idpat.findall(t.group(1))
                continue
            f = func.match(line)
            if f:
                for rid in pending:
                    found.setdefault(rid, []).append(f"{rel}:{f.group(1)}")
                pending = []
            elif pending and line.strip() and not line.strip().startswith("//"):
                pending = []  # tag not directly above a test function
    return found


def scan_manual(path: pathlib.Path, prefix: str):
    found = {}
    if not path.exists():
        return found
    pat = re.compile(rf"^\s*-\s*({prefix}-SRS-\d{{3}})\s*:\s*(.+)$")
    for line in path.read_text(encoding="utf-8").splitlines():
        m = pat.match(line)
        if m:
            found.setdefault(m.group(1), []).append(f"manual: {m.group(2).strip()}")
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--module", default="libredcm")
    ap.add_argument("--prefix", default="DCM")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()

    dhf = ROOT / "docs" / "dhf" / a.module
    reqs = load_requirements(dhf / "SRS.md", a.prefix)
    verif = scan_tests(a.prefix)
    for rid, refs in scan_manual(dhf / "manual-verification.md", a.prefix).items():
        verif.setdefault(rid, []).extend(refs)

    active = {k: v for k, v in reqs.items() if v["status"] == "Active"}
    untested = sorted(k for k in active if k not in verif)
    unknown = sorted(k for k in verif if k not in reqs)
    retired_refs = sorted(k for k in verif if k in reqs and reqs[k]["status"] == "Retired")

    rows = ["| Requirement | Status | Verified by |", "|---|---|---|"]
    for rid in sorted(reqs):
        refs = "<br>".join(f"`{r}`" for r in verif.get(rid, [])) or "**NOT VERIFIED**"
        rows.append(f"| {rid} | {reqs[rid]['status']} | {refs} |")
    summary = (
        f"Requirements: {len(reqs)} ({len(active)} active). "
        f"Active with verification: {len(active) - len(untested)}. "
        f"Active without verification: {len(untested)}. "
        f"Tags pointing at unknown IDs: {len(unknown)}. Tags pointing at retired IDs: {len(retired_refs)}."
    )

    if a.write:
        out = dhf / "generated" / "trace-matrix.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            "# Trace matrix (generated)\n\nGenerated by `scripts/qms/trace.py`. Do not edit by hand.\n\n"
            + summary + "\n\n" + "\n".join(rows) + "\n",
            encoding="utf-8",
        )
        print(f"wrote {out.relative_to(ROOT)}")

    print(summary)
    for rid in untested:
        print(f"  untested: {rid}  {active[rid]['text'][:70]}")
    for rid in unknown:
        print(f"  unknown ID in tests: {rid}")
    for rid in retired_refs:
        print(f"  retired ID still referenced: {rid}")

    if a.check and (untested or unknown or retired_refs):
        sys.exit(1)


if __name__ == "__main__":
    main()
