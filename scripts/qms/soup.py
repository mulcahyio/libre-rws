#!/usr/bin/env python3
"""Generate the SOUP list for a Libre RWS module from go.mod and the SBOM.

Direct dependencies come from go.mod (`require` lines without `// indirect`),
replaced modules (forks/copies) from `replace` lines, licences from the
CycloneDX SBOM if present. Hand-maintained evaluation columns (purpose, risk
class, known-anomaly review, support/EOL) are kept: the script merges them
back in from the existing soup.md by module path.

Usage: soup.py [--module libredcm]
Writes docs/dhf/<module>/soup.md
"""
import argparse
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
EVAL_COLS = ["Purpose", "Risk (SOUP failure → hazard)", "Known anomalies reviewed", "Support / EOL"]
TODO = "TODO"


def parse_gomod():
    text = (ROOT / "go.mod").read_text(encoding="utf-8")
    direct, indirect, replaces = {}, {}, {}
    go_ver = re.search(r"^go\s+(\S+)", text, re.M)
    toolchain = re.search(r"^toolchain\s+(\S+)", text, re.M)
    for block in re.findall(r"require\s*\((.*?)\)", text, re.S) + re.findall(r"^require\s+(\S+\s+\S+.*)$", text, re.M):
        for line in block.splitlines():
            m = re.match(r"\s*(\S+)\s+(v\S+)(.*)$", line)
            if m:
                (indirect if "// indirect" in m.group(3) else direct)[m.group(1)] = m.group(2)
    for m in re.finditer(r"^replace\s+(\S+)\s*=>\s*(\S+)", text, re.M):
        replaces[m.group(1)] = m.group(2)
    return direct, indirect, replaces, (go_ver.group(1) if go_ver else "?"), (toolchain.group(1) if toolchain else None)


def sbom_licences(module):
    path = ROOT / "docs" / "dhf" / module / "generated" / "sbom.cdx.json"
    lic = {}
    if not path.exists():
        return lic
    for c in json.loads(path.read_text()).get("components", []):
        name = c.get("name")
        ids = []
        # cyclonedx-gomod puts detected licences under evidence.licenses
        for l in (c.get("licenses") or []) + ((c.get("evidence") or {}).get("licenses") or []):
            lv = l.get("license", {})
            ids.append(lv.get("id") or lv.get("name") or "")
            if l.get("expression"):
                ids.append(l["expression"])
        lic[name] = ", ".join(i for i in ids if i) or "not detected"
    return lic


def existing_eval(path):
    keep = {}
    if not path.exists():
        return keep
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| `"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        name = cells[0].strip("`")
        if len(cells) >= 4 + len(EVAL_COLS):
            keep[name] = cells[-len(EVAL_COLS):]
    return keep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--module", default="libredcm")
    a = ap.parse_args()
    out = ROOT / "docs" / "dhf" / a.module / "soup.md"
    direct, indirect, replaces, go_ver, toolchain = parse_gomod()
    lic = sbom_licences(a.module)
    keep = existing_eval(out)

    lines = [
        "# SOUP / off-the-shelf software list: " + a.module,
        "",
        "Generated by `scripts/qms/soup.py` from `go.mod` and the CycloneDX SBOM; the four evaluation",
        "columns are maintained by hand and preserved on regeneration. IEC 62304 §5.3.3, §5.3.4, §7.1.3;",
        "FDA *Off-The-Shelf Software Use in Medical Devices* (2023).",
        "",
        f"Go language version: `{go_ver}`" + (f", toolchain `{toolchain}`" if toolchain else "") + ". Runtime image: see `deploy/docker/Dockerfile.dicom` (base images pinned by digest).",
        "",
        "## Direct dependencies",
        "",
        "| Module | Version | Licence | Kind | " + " | ".join(EVAL_COLS) + " |",
        "|---|---|---|---|" + "---|" * len(EVAL_COLS),
    ]
    for name in sorted(direct):
        kind = "SOUP"
        if name in replaces:
            kind = f"**Own software item** (replaced by `{replaces[name]}`; verified as LibreDCM code, not SOUP)"
        ev = keep.get(name, [TODO] * len(EVAL_COLS))
        lines.append(f"| `{name}` | {direct[name]} | {lic.get(name, 'see SBOM')} | {kind} | " + " | ".join(ev) + " |")
    lines += [
        "",
        f"## Indirect dependencies ({len(indirect)})",
        "",
        "Covered through the direct dependency that pulls them in, the SBOM and the vulnerability scan.",
        "",
        "| Module | Version | Licence |",
        "|---|---|---|",
    ]
    for name in sorted(indirect):
        lines.append(f"| {name} | {indirect[name]} | {lic.get(name, 'see SBOM')} |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    todo = sum(1 for n in direct if n not in keep)
    print(f"wrote {out.relative_to(ROOT)}: {len(direct)} direct, {len(indirect)} indirect; {todo} direct without evaluation")


if __name__ == "__main__":
    main()
